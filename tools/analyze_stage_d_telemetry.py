#!/usr/bin/env python3
"""
Analyze Stage D JSONL telemetry generated by stage_d_producer.exe or
stage_d_bridge_selftest.exe and audit:
- Malformed JSON lines (strict failure if bad_lines > 0 or non-dict records)
- Per-row 3-tier frame accounting invariants (I, Q, C, H, gap, starv, drop)
- Monotonic non-decreasing frame/event counters
- Clean shutdown flush invariant (holdback_frames == 0 and C == Q on shutdown_flush)
- Zero IPC overwrite conflict events (and optional underrun/overrun caps)
- Segmented capture-clock vs QPC drift (capture_vs_qpc_ppm) & watermark summary
"""
from __future__ import annotations

import argparse
import json
import math
import os
import statistics
import sys


REQUIRED_INT_FIELDS = (
    "holdback_frames",
    "converted_in_frames_48k",
    "timeline_queued_frames",
    "committed_ring_frames",
    "late_overlap_dropped_frames",
    "source_gap_zero_frames",
    "starvation_zero_frames",
    "wall_elapsed_frames_48k",
)

MONOTONIC_INT_FIELDS = (
    "wall_elapsed_frames_48k",
    "converted_in_frames_48k",
    "timeline_queued_frames",
    "committed_ring_frames",
    "late_overlap_dropped_frames",
    "source_gap_zero_frames",
    "starvation_zero_frames",
    "timestamp_fallback_anchors",
    "packet_count",
    "discontinuity_count",
    "timestamp_error_count",
    "stream_restart_count",
    "ipc_underrun_events",
    "ipc_overrun_events",
    "ipc_overwrite_conflict_events",
)


def _is_strict_int(val) -> bool:
    return isinstance(val, int) and not isinstance(val, bool)


def _reject_nonstandard_constant(token: str):
    raise ValueError(f"Non-standard JSON constant {token!r}")


def _get_int(rec: dict, key: str, default: int = 0) -> int:
    v = rec.get(key, default)
    if _is_strict_int(v):
        return v
    if isinstance(v, float) and not isinstance(v, bool) and math.isfinite(v):
        return int(v)
    return default


def _format_int_or_missing(rec: dict, key: str) -> str:
    if key not in rec:
        return "<missing>"
    v = rec.get(key)
    if _is_strict_int(v):
        return str(v)
    return f"<invalid:{type(v).__name__}>"


def _extract_segments(records: list[dict]) -> list[dict]:
    """
    Partition records into continuous active segments split by stream restarts,
    discontinuities, or timeline gaps/drops, then compute capture_vs_qpc_ppm.
    """
    segments: list[list[dict]] = []
    cur_seg: list[dict] = []
    prev_key = None
    prev_pkt_cnt = None

    for rec in records:
        pkt_cnt = _get_int(rec, "packet_count", 0)
        conv_in = _get_int(rec, "converted_in_frames_48k", 0)
        end_qpc = _get_int(rec, "last_packet_end_qpc_100ns", 0)
        if end_qpc <= 0:
            end_qpc = _get_int(rec, "last_packet_qpc_100ns", 0)

        if pkt_cnt <= 0 or conv_in <= 0 or end_qpc <= 0:
            continue
        if prev_pkt_cnt is not None and pkt_cnt == prev_pkt_cnt:
            continue

        cur_key = (
            _get_int(rec, "stream_restart_count", 0),
            _get_int(rec, "discontinuity_count", 0),
            _get_int(rec, "source_gap_zero_frames", 0),
            _get_int(rec, "starvation_zero_frames", 0),
            _get_int(rec, "late_overlap_dropped_frames", 0),
            _get_int(rec, "timestamp_fallback_anchors", 0),
        )
        if prev_key is not None and cur_key != prev_key:
            if cur_seg:
                segments.append(cur_seg)
                cur_seg = []
        cur_seg.append(rec)
        prev_key = cur_key
        prev_pkt_cnt = pkt_cnt

    if cur_seg:
        segments.append(cur_seg)

    summaries = []
    for idx, seg in enumerate(segments, 1):
        if len(seg) >= 2:
            r0 = seg[0]
            r1 = seg[-1]
            qpc0 = _get_int(r0, "last_packet_end_qpc_100ns", 0) or _get_int(r0, "last_packet_qpc_100ns", 0)
            qpc1 = _get_int(r1, "last_packet_end_qpc_100ns", 0) or _get_int(r1, "last_packet_qpc_100ns", 0)
            d_qpc = qpc1 - qpc0
            d_frames = _get_int(r1, "converted_in_frames_48k") - _get_int(r0, "converted_in_frames_48k")
            if d_qpc > 0 and d_frames > 0:
                expected_48k = (d_qpc * 48000.0) / 10_000_000.0
                ppm = ((d_frames / expected_48k) - 1.0) * 1e6
                summaries.append(
                    {
                        "segment": idx,
                        "rows": len(seg),
                        "duration_s": d_qpc / 10_000_000.0,
                        "frames_48k": d_frames,
                        "expected_48k": expected_48k,
                        "ppm": ppm,
                    }
                )
        elif (
            len(seg) == 1
            and idx == 1
            and _get_int(seg[0], "source_gap_zero_frames", 0) == 0
            and _get_int(seg[0], "starvation_zero_frames", 0) == 0
            and _get_int(seg[0], "late_overlap_dropped_frames", 0) == 0
            and _get_int(seg[0], "stream_restart_count", 0) == 0
        ):
            r = seg[0]
            origin = _get_int(r, "origin_qpc_100ns", 0)
            end_qpc = _get_int(r, "last_packet_end_qpc_100ns", 0) or _get_int(r, "last_packet_qpc_100ns", 0)
            d_qpc = end_qpc - origin
            d_frames = _get_int(r, "converted_in_frames_48k")
            if origin > 0 and d_qpc > 0 and d_frames > 0:
                expected_48k = (d_qpc * 48000.0) / 10_000_000.0
                ppm = ((d_frames / expected_48k) - 1.0) * 1e6
                summaries.append(
                    {
                        "segment": idx,
                        "rows": 1,
                        "duration_s": d_qpc / 10_000_000.0,
                        "frames_48k": d_frames,
                        "expected_48k": expected_48k,
                        "ppm": ppm,
                    }
                )

    return summaries


def analyze(args: argparse.Namespace) -> int:
    path = args.telemetry_jsonl
    if not os.path.exists(path):
        print(f"[ERROR] Telemetry file not found: {path}")
        return 1

    records: list[dict] = []
    bad_lines = 0
    non_dict_lines = 0

    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line_no, raw in enumerate(f, 1):
            stripped = raw.strip()
            if not stripped:
                continue
            try:
                obj = json.loads(stripped, parse_constant=_reject_nonstandard_constant)
            except (json.JSONDecodeError, ValueError) as exc:
                bad_lines += 1
                print(f"[FAIL] Malformed JSON on line {line_no}: {exc}")
                continue
            if not isinstance(obj, dict):
                non_dict_lines += 1
                print(f"[FAIL] Line {line_no} is not a JSON object")
                continue
            records.append(obj)

    if bad_lines > 0 or non_dict_lines > 0:
        print(
            f"[RESULT] FAIL: bad_lines={bad_lines}, non_dict_lines={non_dict_lines}"
        )
        return 1

    if not records:
        print(f"[RESULT] FAIL: telemetry file is empty ({path})")
        return 1

    invariant_violations = []
    monotonic_violations = []
    shutdown_violations = []
    shutdown_rows = []
    overwrite_conflict_max = 0
    underrun_max = 0
    overrun_max = 0

    prev_rec: dict | None = None
    for idx, rec in enumerate(records, 1):
        missing = [k for k in REQUIRED_INT_FIELDS if not _is_strict_int(rec.get(k))]
        if missing:
            invariant_violations.append((idx, f"missing/invalid int fields: {missing}"))
            continue

        h = rec["holdback_frames"]
        i_frames = rec["converted_in_frames_48k"]
        q_frames = rec["timeline_queued_frames"]
        c_frames = rec["committed_ring_frames"]
        drop = rec["late_overlap_dropped_frames"]
        gap = rec["source_gap_zero_frames"]
        starv = rec["starvation_zero_frames"]

        if h < 0 or h > 240:
            invariant_violations.append((idx, f"holdback_frames={h} outside [0, 240]"))
        if q_frames != c_frames + h:
            invariant_violations.append((idx, f"Q({q_frames}) != C({c_frames}) + H({h})"))
        if i_frames < drop:
            invariant_violations.append((idx, f"I({i_frames}) < drop({drop})"))
        if q_frames != (i_frames - drop) + gap + starv:
            invariant_violations.append(
                (idx, f"Q({q_frames}) != (I({i_frames}) - drop({drop})) + gap({gap}) + starv({starv})")
            )

        if prev_rec is not None:
            for field in MONOTONIC_INT_FIELDS:
                cur_v = _get_int(rec, field, 0)
                prev_v = _get_int(prev_rec, field, 0)
                if cur_v < prev_v:
                    monotonic_violations.append((idx, f"{field} regressed {prev_v} -> {cur_v}"))
        prev_rec = rec

        if rec.get("kind") == "shutdown_flush":
            shutdown_rows.append(rec)
            if h != 0 or c_frames != q_frames:
                shutdown_violations.append(
                    (idx, f"shutdown_flush holdback={h} C={c_frames} Q={q_frames}")
                )

        overwrite_conflict_max = max(
            overwrite_conflict_max, _get_int(rec, "ipc_overwrite_conflict_events", 0)
        )
        underrun_max = max(underrun_max, _get_int(rec, "ipc_underrun_events", 0))
        overrun_max = max(overrun_max, _get_int(rec, "ipc_overrun_events", 0))

    last = records[-1]
    wm_all = [_get_int(r, "ipc_watermark_frames", 0) for r in records if "ipc_watermark_frames" in r]
    wm_live = [
        _get_int(r, "ipc_watermark_frames", 0)
        for r in records
        if _get_int(r, "ipc_consumer_active_readers", 0) > 0 or _get_int(r, "ipc_watermark_frames", 0) > 0
    ]
    age_live = [
        _get_int(r, "ipc_last_frame_age_us", 0)
        for r in records
        if _get_int(r, "ipc_last_frame_age_us", 0) > 0
    ]

    segments = _extract_segments(records)
    longest_seg = max(segments, key=lambda s: s["frames_48k"]) if segments else None

    c_json = (bad_lines == 0 and non_dict_lines == 0)
    c_inv = (len(invariant_violations) == 0)
    c_mono = (len(monotonic_violations) == 0)
    c_shutdown_inv = (len(shutdown_violations) == 0)
    c_shutdown_req = (not args.require_clean_shutdown) or (len(shutdown_rows) >= 1)
    c_conflicts = (overwrite_conflict_max == 0)
    c_underruns = (args.max_underruns is None) or (underrun_max <= args.max_underruns)
    c_overruns = (args.max_overruns is None) or (overrun_max <= args.max_overruns)

    c_ppm = True
    measured_ppm = longest_seg["ppm"] if longest_seg else None
    if args.expect_ppm is not None:
        if measured_ppm is None:
            c_ppm = False
        else:
            c_ppm = abs(measured_ppm - args.expect_ppm) <= args.ppm_tolerance

    print(f"=== Stage D Telemetry Audit ({len(records)} records, {bad_lines} malformed) ===")
    print(f"  Target EXE / Format     : {last.get('target_exe', '')} (PID={last.get('target_pid', 0)}), {last.get('format', '')}")
    print(
        f"  Final Counters (frames) : wall={_format_int_or_missing(last, 'wall_elapsed_frames_48k')} "
        f"I={_format_int_or_missing(last, 'converted_in_frames_48k')} "
        f"Q={_format_int_or_missing(last, 'timeline_queued_frames')} "
        f"C={_format_int_or_missing(last, 'committed_ring_frames')} "
        f"H={_format_int_or_missing(last, 'holdback_frames')}"
    )
    print(
        f"  Gap / Starv / Drop      : gap={_format_int_or_missing(last, 'source_gap_zero_frames')} "
        f"starv={_format_int_or_missing(last, 'starvation_zero_frames')} "
        f"late_drop={_format_int_or_missing(last, 'late_overlap_dropped_frames')} "
        f"ts_fallback={_get_int(last, 'timestamp_fallback_anchors')}"
    )
    print(
        f"  IPC Events              : conflicts={overwrite_conflict_max} underruns={underrun_max} "
        f"overruns={overrun_max} readers={_get_int(last, 'ipc_consumer_active_readers')}"
    )

    wm_src = wm_live if wm_live else wm_all
    if wm_src:
        print(
            f"  Watermark (frames)      : min={min(wm_src)} median={statistics.median(wm_src):.1f} max={max(wm_src)}"
        )
    if age_live:
        print(
            f"  Frame Age (us)          : min={min(age_live)} median={statistics.median(age_live):.1f} max={max(age_live)}"
        )

    if segments:
        print("\n[Segments & Clock Drift]:")
        for seg in segments:
            print(
                f"  Seg #{seg['segment']}: rows={seg['rows']} dur={seg['duration_s']:.3f}s "
                f"frames={seg['frames_48k']} expected={seg['expected_48k']:.2f} "
                f"capture_vs_qpc_ppm={seg['ppm']:+.3f}"
            )
    else:
        print("\n[Segments & Clock Drift]: <no multi-packet continuous segment recorded>")

    e1_rows = [r for r in records if "e1_headline" in r]
    if e1_rows:
        headline_seq: list[str] = []
        routing_seq: list[str] = []
        conflict_rows = 0
        audible_peaks: list[float] = []
        audible_rms: list[float] = []
        max_silent_ms = 0

        for r in e1_rows:
            hl = str(r.get("e1_headline", ""))
            if hl and (not headline_seq or headline_seq[-1] != hl):
                headline_seq.append(hl)
            rt = str(r.get("e1_routing", ""))
            if rt and (not routing_seq or routing_seq[-1] != rt):
                routing_seq.append(rt)
            if r.get("e1_routing_conflict") is True:
                conflict_rows += 1
            if _get_int(r, "e1_audible_frames_1s", 0) > 0:
                pk = r.get("e1_peak_dbfs_1s")
                rm = r.get("e1_rms_dbfs_1s")
                if isinstance(pk, (int, float)) and not isinstance(pk, bool):
                    audible_peaks.append(float(pk))
                if isinstance(rm, (int, float)) and not isinstance(rm, bool):
                    audible_rms.append(float(rm))
            max_silent_ms = max(max_silent_ms, _get_int(r, "e1_continuous_silent_ms", 0))

        last_e1 = e1_rows[-1]
        print("\n[Stage E1 Diagnostics]:")
        print(f"  Headline Transitions    : {' -> '.join(headline_seq)}")
        print(f"  Routing Transitions     : {' -> '.join(routing_seq)}")
        print(
            f"  Final Endpoints         : target={last_e1.get('e1_target_endpoint', '')!r} "
            f"| default={last_e1.get('e1_default_endpoint', '')!r}"
        )
        print(
            f"  Routing Conflict Rows   : {conflict_rows}/{len(e1_rows)} "
            f"| Max Active-Silent: {max_silent_ms} ms"
        )
        if audible_peaks and audible_rms:
            print(
                f"  Audible Level (1s dBFS) : peak=[{min(audible_peaks):.1f}, {statistics.median(audible_peaks):.1f}, {max(audible_peaks):.1f}] "
                f"rms=[{min(audible_rms):.1f}, {statistics.median(audible_rms):.1f}, {max(audible_rms):.1f}]"
            )

    print("\n[Audit Checks]:")
    print(f"  [{'PASS' if c_json else 'FAIL'}] Malformed / non-dict lines       : {bad_lines + non_dict_lines}")
    print(f"  [{'PASS' if c_inv else 'FAIL'}] 3-tier algebraic invariants        : {len(invariant_violations)} violation(s)")
    print(f"  [{'PASS' if c_mono else 'FAIL'}] Monotonic counter progression      : {len(monotonic_violations)} violation(s)")
    print(f"  [{'PASS' if c_shutdown_inv else 'FAIL'}] shutdown_flush H==0 && C==Q        : {len(shutdown_violations)} violation(s) ({len(shutdown_rows)} row(s))")
    if args.require_clean_shutdown:
        print(f"  [{'PASS' if c_shutdown_req else 'FAIL'}] Clean shutdown_flush present       : {len(shutdown_rows)} row(s)")
    print(f"  [{'PASS' if c_conflicts else 'FAIL'}] ipc_overwrite_conflict_events == 0 : {overwrite_conflict_max}")
    if args.max_underruns is not None:
        print(f"  [{'PASS' if c_underruns else 'FAIL'}] ipc_underrun_events <= {args.max_underruns:<11}: {underrun_max}")
    if args.max_overruns is not None:
        print(f"  [{'PASS' if c_overruns else 'FAIL'}] ipc_overrun_events <= {args.max_overruns:<12}: {overrun_max}")
    if args.expect_ppm is not None:
        ppm_str = f"{measured_ppm:+.3f}" if measured_ppm is not None else "N/A"
        print(
            f"  [{'PASS' if c_ppm else 'FAIL'}] capture_vs_qpc_ppm near {args.expect_ppm:+.1f}+/-{args.ppm_tolerance:.1f} : {ppm_str}"
        )

    for label, vlist in (
        ("Invariant violations", invariant_violations),
        ("Monotonic violations", monotonic_violations),
        ("Shutdown violations", shutdown_violations),
    ):
        for row_idx, msg in vlist[:10]:
            print(f"    [DETAIL] {label} row {row_idx}: {msg}")

    all_ok = (
        c_json
        and c_inv
        and c_mono
        and c_shutdown_inv
        and c_shutdown_req
        and c_conflicts
        and c_underruns
        and c_overruns
        and c_ppm
    )
    print(f"\n[RESULT] {'PASS' if all_ok else 'FAIL'}")
    return 0 if all_ok else 1


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Analyze Stage D producer/selftest JSONL telemetry."
    )
    parser.add_argument("telemetry_jsonl", help="Path to Stage D JSONL telemetry file.")
    parser.add_argument(
        "--expect-ppm",
        type=float,
        default=None,
        help="Expected capture_vs_qpc_ppm value to validate against.",
    )
    parser.add_argument(
        "--ppm-tolerance",
        type=float,
        default=15.0,
        help="Tolerance in ppm for --expect-ppm check (default: 15.0).",
    )
    parser.add_argument(
        "--require-clean-shutdown",
        action="store_true",
        help="Require at least one shutdown_flush event with H==0 and C==Q.",
    )
    parser.add_argument(
        "--max-underruns",
        type=int,
        default=None,
        help="Maximum allowed ipc_underrun_events.",
    )
    parser.add_argument(
        "--max-overruns",
        type=int,
        default=None,
        help="Maximum allowed ipc_overrun_events.",
    )
    return analyze(parser.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
